def check(sudoku, x, y, val):
    for i in range(9):
        if sudoku[x][i] == val:
            return False
    for i in range(9):
        if sudoku[i][y] == val:
            return False
    subRow = x - (x%3)
    subCol = y - (y%3)
    for j in range(3):
        for k in range(3):
            if sudoku[k + subRow][j + subCol] == val:
                return False
    return True

def solver(sudoku, domain, x, y):
    if y > 8:
        x += 1
        y = 0
    if x > 8:
        for row in sudoku:
            print(" ".join(map(str, row)))
        return True
    else:
        if sudoku[x][y] == 0:
            for num in domain:
                if check(sudoku, x, y, num):
                    sudoku[x][y] = num
                    if solver(sudoku, domain, x, y+1):
                        return True
                    sudoku[x][y] = 0
            return False
        else:
            return solver(sudoku, domain, x, y+1)
   



        

def main():
    domain = [1, 2, 3, 4, 5, 6, 7, 8, 9]        # defines the domain for the sudoku in main so it can be passed as a parameter into the solver function
    sudoku = retrieveSudoku()       # initialises a 2D array sudoku to store the initial sudoku grid, this then is passed as a parameter into the solver function
    #domainDict = calcDomains(sudoku, domain)
